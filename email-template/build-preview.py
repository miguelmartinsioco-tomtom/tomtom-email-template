#!/usr/bin/env python3
"""Copy the email template into template-embed.js so preview.html works without a server.

Browsers block a page opened from disk (file://) from reading another file, so
preview.html can't measure the sections of tomtom-email-template.html directly.
This script stores the template's HTML in template-embed.js, which preview.html
loads with a plain <script> tag (allowed from disk).

Run it after every change to tomtom-email-template.html:

    python3 build-preview.py
"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
html = (here / "tomtom-email-template.html").read_text(encoding="utf-8")

out = here / "template-embed.js"
out.write_text(
    "// Generated by build-preview.py from tomtom-email-template.html. Do not edit by hand.\n"
    "window.TEMPLATE_HTML = " + json.dumps(html, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print(f"Wrote {out.name} ({len(html):,} characters)")
